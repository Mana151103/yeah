#include<unistd.h>

void	ft_putnbr(int n)
{
	char	a;
	long	nb;

	nb = n;
	if (nb < 0)
	{
		nb *= -1;
		write (1, "-", 1);
	}
	if (nb / 10)
		ft_putnbr(nb / 10);
	a = nb % 10 + '0';
	write (1, &a, 1);
}
