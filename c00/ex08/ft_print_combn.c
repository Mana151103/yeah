#include <unistd.h>

void	ft_print_combn(int n)
{
	int		i;
	int		j;
	char	*a;

	i = n;
	while (i)
	{
		while (j)
		{
			a[n - (j - 1)] = '0' + a[n - j];
			j--;
		}
		i--;
	}
}